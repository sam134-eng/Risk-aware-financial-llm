"""Export the grounding & evaluation results for the paper's Overleaf project (AAAI 2027 template).

Writes overleaf/ with
  tables/*.tex   tabular tables (no extra packages: plain \\hline, \\small)
  Figures/*.pdf  figures copied from results/plots/
  notes_evaluation.tex      3-4 findings + provenance per experiment (\\input it, or paste into notes.tex)
All numbers are read from the result files; nothing is typed by hand.

Usage: python -m src.reporting.export_latex [--commit <hash of the analysis code>]
"""
from __future__ import annotations

import argparse, csv, hashlib, json, shutil
from pathlib import Path

OUT = Path("overleaf")
BENCH = Path("data/combined_benchmark_500.json")


def esc(s) -> str:
    s = str(s)
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"), ("#", r"\#"),
                 ("_", r"\_"), ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"), ("^", r"\^{}")):
        s = s.replace(a, b)
    return s


def pct(a, b, d=1):
    return f"{100 * a / b:.{d}f}\\% ({a}/{b})" if b else "--"


def table(name, caption, label, header, rows, colspec, wide=False, note=None):
    env = "table*" if wide else "table"
    L = [f"% generated by src/reporting/export_latex.py -- do not edit numbers by hand",
         f"\\begin{{{env}}}[t]", "\\centering", "\\small"] + ([] if wide else ["\\setlength{\\tabcolsep}{4pt}"]) + [
         f"\\begin{{tabular}}{{{colspec}}}", "\\hline",
         " & ".join(f"\\textbf{{{h}}}" for h in header) + " \\\\", "\\hline"]
    for r in rows:
        if r == "---":
            L.append("\\hline")
        else:
            L.append(" & ".join(r) + " \\\\")
    L += ["\\hline", "\\end{tabular}"]
    cap = caption + (f" {note}" if note else "")
    L += [f"\\caption{{{cap}}}", f"\\label{{{label}}}", f"\\end{{{env}}}", ""]
    (OUT / "tables" / f"{name}.tex").write_text("\n".join(L))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--commit", default="\\textit{(fill in)}", help="git commit of the analysis code (your PR branch)")
    a = ap.parse_args()
    fill_extra = {}
    (OUT / "tables").mkdir(parents=True, exist_ok=True)
    (OUT / "Figures").mkdir(parents=True, exist_ok=True)
    bench_sha = hashlib.sha256(BENCH.read_bytes()).hexdigest()

    ans = json.loads(Path("results/evaluation/answer_eval_summary.json").read_text())
    tax = json.loads(Path("results/analysis/error_taxonomy_80_summary.json").read_text())
    inj = json.loads(Path("results/grounding/grounding_eval_summary.json").read_text())
    s1g = json.loads(Path("results/grounding/stage1_v2_grounding_summary.json").read_text())
    s1 = json.loads(Path("experiments/stage1_v2/FinVerify_SMT_Stage1_v2_80_Case_Results.json").read_text())["summary"]

    # ---- Table A: GPT-4o-mini answer accuracy + Z3 verdict vs correctness
    ver = tax["original_verifier_status_vs_answer_correct_500"]
    a500, a80 = ans["all_500"], ans["selected_80"]
    rows = [
        ["All cases (FinQA test subset)", str(a500["lenient"]["n"]), pct(a500["lenient"]["correct"], a500["lenient"]["n"]),
         pct(a500["strict"]["correct"], a500["strict"]["n"])],
        ["80 selected NOT\\_APPLICABLE cases", str(a80["lenient"]["n"]), pct(a80["lenient"]["correct"], a80["lenient"]["n"]),
         pct(a80["strict"]["correct"], a80["strict"]["n"])],
        "---",
        ["Z3 verdict PASS", str(ver["PASS"]["cases"]), pct(ver["PASS"]["answer_correct"], ver["PASS"]["cases"]), "--"],
        ["Z3 verdict FAIL", str(ver["FAIL"]["cases"]), pct(ver["FAIL"]["answer_correct"], ver["FAIL"]["cases"]), "--"],
        ["Z3 verdict NOT\\_APPLICABLE", str(ver["NOT_APPLICABLE"]["cases"]),
         pct(ver["NOT_APPLICABLE"]["answer_correct"], ver["NOT_APPLICABLE"]["cases"]), "--"],
    ]
    table("answer_accuracy", "GPT-4o-mini final-answer accuracy against FinQA gold (deterministic Python "
          "evaluator), overall and split by the original Z3 verifier verdict.", "tab:answer-accuracy",
          ["Subset", "$n$", "Lenient", "Strict"], rows, "lrrr", wide=True,
          note="Lenient: equal at gold precision, within 1\\%, or sign stated in words; strict: equal at gold precision. "
               "17 cases with multi-part gold answers are not scored.")

    # ---- Table B: accuracy by reasoning pattern
    pat = {k: v for k, v in ans["by_reasoning_pattern"].items() if v["n"]}
    rows = [[esc(k.replace("_", " ")), str(v["n"]), f"{100 * v['accuracy']:.1f}\\%"]
            for k, v in sorted(pat.items(), key=lambda kv: -kv[1]["n"])]
    table("accuracy_by_pattern", "GPT-4o-mini lenient answer accuracy by reasoning pattern "
          "(pattern derived from the FinQA reference program).", "tab:pattern",
          ["Pattern", "$n$", "Accuracy"], rows, "lrr")

    # ---- Table C: grounding checker validation (error injection)
    names = {"baseline": "No error (reference IR)", "scale_x1000": "Value $\\times$1000",
             "sign_flip": "Sign flipped", "transcription": "Last digit changed",
             "wrong_reference": "Points to other evidence", "missing_source": "Source removed",
             "wrong_period_cited": "Neighbouring cell used and cited"}
    rows = [[names.get(k, esc(k)), esc(v["expected_status"]), f"{v['as_expected']}/{v['evaluated']}",
             f"{100 * v['rate']:.1f}\\%"] for k, v in inj["conditions"].items()]
    table("grounding_validation", "Evidence grounding checker on reference IR built from FinQA gold programs "
          "with one injected error per case.", "tab:grounding-validation",
          ["Condition", "Expected", "As expected", "Rate"], rows, "llrr", wide=True,
          note="The last row passes by design: grounding cannot detect a wrong period that is cited correctly.")

    # ---- Table D: Stage 1 v2 equations (Chaewon) grounded
    m = s1g["input_match_classes"]
    direct = sum(v for k, v in m.items() if k in ("EVIDENCE_EXACT", "EVIDENCE_SCALED", "EVIDENCE_RESCALED",
                                                   "EVIDENCE_PERCENT_AS_RATIO", "EVIDENCE_SIGN_DIFFERS",
                                                   "EVIDENCE_ROUNDED", "QUESTION"))
    n_in = sum(m.values())
    cross = tax["arithmetic_vs_answer_on_extracted_equations"]
    both = cross.get("ALL_CHECKED_PASS|inputs_supported", {"cases": 0, "answer_correct": 0})
    rows = [
        ["Cases with extracted equations", f"{s1['cases_with_expressions']}/80"],
        ["Equations / inputs", f"{s1['total_extracted_equations']} / {n_in}"],
        ["Inputs found directly in evidence", pct(direct, n_in)],
        ["Inputs derived from one evidence item", str(m.get("DERIVED_FROM_EVIDENCE", 0))],
        ["Inputs reused from an earlier step", str(m.get("MODEL_INTERMEDIATE", 0))],
        ["Inputs not found", str(m.get("NOT_FOUND", 0))],
        "---",
        ["Arithmetic PASS and inputs grounded", f"{both['cases']} cases"],
        ["\\quad of which answer matches gold", pct(both["answer_correct"], both["cases"])],
    ]
    table("stage1_grounding", "Grounding of the equations Stage~1~v2 extracted from GPT-4o-mini answers "
          "(80-case set; no gold used for grounding).", "tab:stage1-grounding", ["Measure", "Value"], rows, "lr")

    # ---- Table E: gold audit
    gc = ans["gold_consistency_finqa"]
    from collections import Counter
    from src.evaluation.gold_adjudication import ADJUDICATION
    adj = Counter(v[0] for v in ADJUDICATION.values())
    adj_rows = [["\\quad gold answer wrong", str(adj["ANSWER_WRONG"])],
                ["\\quad reference program wrong", str(adj["PROGRAM_WRONG"])],
                ["\\quad both wrong", str(adj["BOTH_WRONG"])],
                ["\\quad ambiguous question", str(adj["AMBIGUOUS"])]]
    rows = []
    for k, v in sorted(gc.items(), key=lambda kv: -kv[1]):
        rows.append([esc(k.replace("_", " ").lower()), str(v)])
        if k == "INCONSISTENT":
            rows += adj_rows
    table("gold_audit", "FinQA gold answers compared with their own reference programs (484 FinQA cases); "
          "inconsistent cases adjudicated by hand against the evidence.",
          "tab:gold-audit", ["Result", "Cases"], rows, "lr",
          note="Not checked: table operations and yes/no answers.")
    fill_extra.update(adj_answer=adj["ANSWER_WRONG"], adj_program=adj["PROGRAM_WRONG"],
                      adj_both=adj["BOTH_WRONG"], adj_amb=adj["AMBIGUOUS"])

    # ---- Table F: pilot 3-shot vs 8-shot (if present)
    pilot = Path("results/pilot_16/pilot_comparison.json")
    if pilot.exists():
        pj = json.loads(pilot.read_text())
        final = Path("results/pilot_16/final_dc8ce86.json")
        fj = json.loads(final.read_text()) if final.exists() else None
        src = fj["metrics"] if fj else pj["metrics"]
        mm = {int(k): v for k, v in src.items()}
        def row(lab, f):
            return [lab, f(mm[3]), f(mm[8])]
        cpct = lambda a, b: f"{a}/{b} ({100 * a / b:.0f}\\%)" if b else "--"
        rows = [
            row("Abstained (empty IR)", lambda x: f"{x['abstain']}/16"),
            row("Input variables", lambda x: str(x["variables"])),
            row("Grounding errors", lambda x: str(x["grounding_errors"])),
            row("Unsourced inputs", lambda x: str(x["unsourced"])),
            row("Validator arith.\\ mismatch", lambda x: f"{x['validator_status'].get('ARITHMETIC_MISMATCH', 0)}/16"),
            row("\\quad IR equations correct", lambda x: f"{x['claim_mismatch_with_correct_equations']}/{x['claim_mismatch']}"),
            row("Formalization acc.", lambda x: cpct(x["computed_correct"], x["scored"])),
            row("\\quad excl.\\ disputed gold", lambda x: cpct(x["computed_correct_clean_gold"], x["scored_clean_gold"])),
        ]
        cost = fj.get("cost_note") if fj else None
        table("pilot_3v8", "Autoformalization pilot: 3-shot vs 8-shot on 16 cases (gpt-6.2-sol). Formalization "
              "accuracy scores the value computed by executing the IR equations in Python against gold.",
              "tab:pilot", ["Measure", "3-shot", "8-shot"], rows, "lrr",
              note=esc(cost) if cost else None)

    # ---- Figures
    for f in ("fig2_verification_vs_answer_correctness", "fig3_accuracy_by_reasoning_pattern", "fig4_80_case_funnel",
              "fig5_grounding_vs_answer_accuracy", "fig6_error_distribution_80", "fig7_grounding_checker_injection",
              "fig1_answer_outcomes"):
        for ext in (".pdf", ".png"):
            p = Path("results/plots") / (f + ext)
            if p.exists():
                shutil.copy(p, OUT / "Figures" / (f + ext))

    # ---- notes.tex
    pilot_note = Path("results/pilot_16/final_notes.tex")
    fill_extra["adj_both_amb"] = fill_extra["adj_both"] + fill_extra["adj_amb"]
    notes = fill(NOTES, **fill_extra, commit=a.commit, bench=bench_sha[:16],
                         a500=pct(a500["lenient"]["correct"], a500["lenient"]["n"]),
                         a80=pct(a80["lenient"]["correct"], a80["lenient"]["n"]),
                         zpass=pct(ver["PASS"]["answer_correct"], ver["PASS"]["cases"]),
                         zna=pct(ver["NOT_APPLICABLE"]["answer_correct"], ver["NOT_APPLICABLE"]["cases"]),
                         gold_bad=gc.get("INCONSISTENT", 0),
                         inj_base=f"{inj['conditions']['baseline']['as_expected']}/{inj['conditions']['baseline']['evaluated']}",
                         direct=pct(direct, n_in), notfound=m.get("NOT_FOUND", 0), both=both["cases"],
                         both_ok=both["answer_correct"],
                         pilot=pilot_note.read_text() if pilot_note.exists() else
                         "\\paragraph{E4. Autoformalization pilot.} \\textit{Pending the final F\\_015 rerun on dc8ce86.}\n")
    (OUT / "notes_evaluation.tex").write_text("\\begingroup\\sloppy\n" + notes.rstrip() + "\n\\par\\endgroup\n")
    print(sorted(str(p.relative_to(OUT)) for p in OUT.rglob("*") if p.is_file()))


def fill(template, **kw):
    for k, v in kw.items():
        template = template.replace("<<" + k + ">>", str(v))
    return template


NOTES = r"""% Grounding & evaluation -- findings and provenance (generated by src/reporting/export_latex.py)
% Analysis code: branch grounding-evaluation, commit <<commit>>
% Benchmark: data/combined_benchmark_500.json, SHA-256 <<bench>>...
% Two evaluation layers are reported separately: (i) Python IR execution + deterministic answer
% evaluator (src/evaluation/ir_executor.py, answer_evaluator.py) and (ii) Z3 SMT verification (Sam's verifier).

\paragraph{E1. Evidence grounding checker (validation).}
\begin{itemize}
\item Deterministic checker that ties every IR number to a table cell or text span (formats, signs, \%, stated scale).
\item On reference IR from 468 FinQA gold programs it returns PASS for <<inj_base>>; the rest are gold programs that
  write a filing fact as a constant. It detects 100\% of injected $\times$1000, sign and wrong-reference errors
  (Table~\ref{tab:grounding-validation}).
\item Limitation: a wrong year that is \emph{cited} correctly passes grounding by design; grounding is not answer correctness.
\item Provenance: \texttt{src/experiments/run\_grounding\_evaluation.py}; no model; FinQA cases of the 500-case benchmark; commit <<commit>>.
\end{itemize}

\paragraph{E2. GPT-4o-mini answers: Python evaluator vs Z3 verdict.}
\begin{itemize}
\item Lenient answer accuracy <<a500>> on all scored cases and <<a80>> on the 80 NOT\_APPLICABLE cases
  (Table~\ref{tab:answer-accuracy}).
\item A Z3 PASS does not imply a correct answer: <<zpass>> of PASS cases match gold vs <<zna>> of NOT\_APPLICABLE cases
  (Z3 checks the stated arithmetic, not the financial question).
\item <<gold_bad>> of 484 FinQA gold answers disagree with their own reference program. Checked by hand against the
  evidence: in <<adj_answer>> the gold answer is wrong (e.g.\ F\_151 3829 vs 38290), in <<adj_program>> the program is wrong but
  the answer right (e.g.\ F\_222), <<adj_both>> are wrong on both sides and <<adj_amb>> is ambiguous
  (Table~\ref{tab:gold-audit}). Only the <<adj_both_amb>> without a reliable reference need excluding.
\item Provenance: model gpt-4o-mini (stored answers, \texttt{results/verification\_results.json});
  \texttt{src/experiments/run\_answer\_evaluation.py} (Python evaluator; Z3 verdicts from the original verifier); commit <<commit>>.
\end{itemize}

\paragraph{E3. Grounding of Stage~1~v2 equations (80 cases).}
\begin{itemize}
\item Of the equation inputs Stage~1~v2 extracted, <<direct>> appear directly in the evidence; <<notfound>> are not found
  (Table~\ref{tab:stage1-grounding}).
\item <<both>> cases have all-PASS arithmetic and fully grounded inputs, but only <<both_ok>> match gold: most of the rest
  have disputed gold answers, and F\_089 uses the wrong denominator -- an error neither grounding nor arithmetic checks catch.
\item Provenance: \texttt{src/experiments/run\_stage1\_grounding.py} on Chaewon's Stage~1~v2 results; no gold used for grounding; commit <<commit>>.
\end{itemize}

<<pilot>>"""

if __name__ == "__main__":
    main()
